import { writeFile } from 'node:fs/promises';
import { etld } from '../extension/core/etld.js';
import { siteKey } from '../extension/core/site-key.js';

// Single-label suffixes are already covered by siteKey's implicit wildcard.
const suffixes = etld.filter(rule => rule.includes('.')).map(rule => {
  const prefix = rule.startsWith('!') ? '!' : rule.startsWith('*.') ? '*.' : '';
  return prefix + new URL('https://' + rule.slice(prefix.length)).hostname.toLowerCase();
});
export const source = '// Generated by scripts/build-stay-site-key.mjs; curated PSL, MPL-2.0.\n'
  + '(() => { const suffixes = new Set(' + JSON.stringify(suffixes) + '); const rules = () => suffixes;\n'
  + siteKey.toString() + '\nglobalThis[Symbol.for("cosmic-gemini.stay-site-key")] = siteKey; })();\n';
await writeFile(new URL('../extension/content/website-fixer-site-key.js', import.meta.url), source);
